/**
 * The stub runner.
 *
 * It writes the evidence files the REAL runner writes, so the sequencer's
 * aggregate evaluation sees the same shape. The mode decides the disposition
 * and, in the mutation modes, exactly one thing that must be refused.
 */
function makeStubRunner({ mode }) {
  // The generated stub lives in an OWNED temporary directory, so its imports
  // of the real library are ABSOLUTE.
  const registryUrl = new URL("../lib/registry.mjs", import.meta.url).href;
  const stubModuleUrl = new URL("./_fixtures/contract_shaped_stub.mjs", import.meta.url).href;
  fs.mkdirSync(path.dirname(stubRunnerPath), { recursive: true, mode: 0o700 });
  const script = `
import fs from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { ACTIVE_REGISTRY_SHA256, FROZEN_SIX, RESERVE_SOURCES } from ${JSON.stringify(registryUrl)};
import { STUB_MUTATIONS, writeContractShapedEvidence } from ${JSON.stringify(stubModuleUrl)};
const argv = process.argv.slice(2);
function getArg(name) {
  const prefix = \`--\${name}=\`;
  for (const a of argv) if (a.startsWith(prefix)) return a.slice(prefix.length);
  return null;
}
const order = getArg("order");
const bvid = getArg("bvid");
const runId = getArg("run-id");
const evidenceRoot = getArg("evidence-root");
const dir = path.join(evidenceRoot, \`bvid-\${order}-\${bvid}\`);
fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
const mode = process.env.STUB_MODE || "${mode}";
const modePerBvid = process.env.STUB_MODE_PER_BVID
  ? JSON.parse(process.env.STUB_MODE_PER_BVID)
  : null;
const finalMode = modePerBvid ? (modePerBvid[bvid] || mode) : mode;
const blockedMutation = finalMode.startsWith("blocked-");
const disposition = blockedMutation
  ? "blocked"
  : (["complete", "limited", "blocked", "failed"].includes(finalMode) ? finalMode : "complete");
const finishReason = \`stub-mode=\${finalMode}\`;

// The CI2 mutations are injected into the WRITTEN evidence, never into the
// oracle. The positive modes carry the COMPLETE contract-shaped facts.
const mutationName = finalMode.replace(/^(ci2|ai1|ai2)-/, "");
const ci2Mutation = STUB_MUTATIONS.includes(mutationName) ? mutationName : "none";
const reachedSynthesis = disposition !== "blocked";
writeContractShapedEvidence({
  dir,
  order,
  bvid,
  runId,
  stageRoot: process.env.NAVIA_B5_STAGE_ROOT || null,
  mutation: ci2Mutation,
  requestCount: 3,
  disposition,
  reachedSynthesis,
});

// The stop-branch knobs. They change the WRITTEN evidence, never the oracle.
if (process.env.STUB_MUTE_AUDIO === "0") {
  fs.writeFileSync(path.join(dir, "chrome_launch.log"), "pid=12345 cdpPort=null profileRef=stub\\n--mute-audio present: false\\n");
}
if (process.env.STUB_SECRET_HIT === "1") {
  fs.writeFileSync(path.join(dir, "secret_scan.csv"), "file_ref,classification,occurrences\\nfile-ref:stub,secret-pattern-0,1\\n");
}

const receiptPath = path.join(dir, "b5-source-receipt.json");
const receiptBvid = finalMode === "identity-mismatch"
  ? FROZEN_SIX.find((entry) => entry.order !== order).bvid
  : finalMode === "reserve-used" ? RESERVE_SOURCES[0].bvid : bvid;
if (finalMode !== "missing-receipt" && fs.existsSync(receiptPath)) {
  const machineReceipt = JSON.parse(fs.readFileSync(receiptPath, "utf8"));
  // A field that the shared writer REMOVED stays removed: the mutation must
  // not be undone here.
  if ("bvid" in machineReceipt) machineReceipt.bvid = receiptBvid;
  if ("runId" in machineReceipt && finalMode === "cross-run") machineReceipt.runId = "another-run-id";
  if ("registrySha256" in machineReceipt && finalMode === "stale-artifact") machineReceipt.registrySha256 = "0".repeat(64);
  if ("uploadCounters" in machineReceipt && finalMode === "upload-violation") machineReceipt.uploadCounters.rawVideoUploadCount = 1;
  if (finalMode === "missing-receipt") fs.rmSync(receiptPath, { force: true });
  fs.writeFileSync(receiptPath, JSON.stringify(machineReceipt, null, 2));
}
if (finalMode === "missing-receipt") fs.rmSync(receiptPath, { force: true });
if (finalMode === "missing-evidence") {
  fs.rmSync(path.join(dir, "receipt.json"), { force: true });
}
if (finalMode === "owned-leak") {
  // A descendant that OUTLIVES the runner. The OWNED audit must see it: it
  // is a descendant of THIS sequencer's child.
  const sleeper = spawn("sleep", ["30"], { stdio: "ignore", detached: true });
  sleeper.unref();
  await new Promise((resolve) => setTimeout(resolve, 900));
}
if (finalMode === "owned-leak-late") {
  // A descendant that survives the SOURCE boundary but exits BEFORE the
  // final closeout. The sighting must be preserved anyway.
  const sleeper = spawn("sleep", ["3"], { stdio: "ignore", detached: true });
  sleeper.unref();
  await new Promise((resolve) => setTimeout(resolve, 700));
}
process.exit(disposition === "failed" ? 1 : 0);
`;
  fs.writeFileSync(stubRunnerPath, script);
  return stubRunnerPath;
}

/**
 * A sequencer copy that points at the stub runner.
 *
 * The copy lives in a UNIQUE, OWNED temporary directory and it is deleted
 * when the test finishes: no generated artefact lands in the repository.
 */
function writeAlternateSequencer({ runnerAbsPath }) {
  return createSequencerCopy({
    repoRoot,
    sequencerPath,
    runnerAbsPath,
    prefix: "navia-b5-seqtest-",
  });
}

/**
 * The environment of ONE sequencer invocation.
 *
 * The sequencer OWNS the one-shot authorization, so every invocation gets a
 * FRESH authorization and a FRESH owned stage root: no test can consume
 * another test's authorization.
 */
function sequencerEnv({ stubMode, stubPerBvid = null, extra = {} } = {}) {
  const stageRoot = makeTempRoot("navia-b5-3-seqstage-");
  fs.chmodSync(stageRoot, 0o700);
  return {
    ...process.env,
    STUB_MODE: stubMode,
    STUB_MODE_PER_BVID: stubPerBvid ? JSON.stringify(stubPerBvid) : "",
    NAVIA_CHROME_MUTE_AUDIO: "1",
    NAVIA_B5_STAGE_ROOT: stageRoot,
    NAVIA_B5_AUTHORIZATION_ID: `authorization-${randomUUID()}`,
    ...extra,
  };
}

function driveSequencer({ stubMode, stubPerBvid = null, evidenceRoot, envOverrides = {} }) {
  makeStubRunner({ mode: stubMode });
  const altSequencer = writeAlternateSequencer({ runnerAbsPath: stubRunnerPath });
  try {
    const proc = spawnSync("node", [altSequencer.path, `--run-id=test-${randomUUID().slice(0, 8)}`, `--evidence-root=${evidenceRoot}`], {
      cwd: repoRoot,
      encoding: "utf8",
      env: sequencerEnv({ stubMode, stubPerBvid, extra: envOverrides }),
    });
    return proc;
  } finally {
    altSequencer.dispose();
  }
}

function summaryOf(evidenceRoot) {
  return JSON.parse(fs.readFileSync(path.join(evidenceRoot, "sequencer-summary.json"), "utf8"));
}

