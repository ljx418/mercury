test("the summary reports the action ledger without double counting", () => {
  const evidenceRoot = makeEvidenceRoot();
  driveSequencer({ stubMode: "complete", evidenceRoot });
  const summary = summaryOf(evidenceRoot);
  const ledger = summary.actionLedger;
  assert.ok(ledger, "the summary must carry the action ledger");
  assert.equal(ledger.ledgerIntegrityOk, true);
  // The CANDIDATE totals and the STAGE lifetime totals are different numbers.
  assert.ok(ledger.candidateTotals, "the candidate totals must be reported");
  assert.ok(ledger.stageTotals, "the stage lifetime totals must be reported");
  // The HISTORICAL lower bound comes from the retained logs of the earlier
  // attempts: it is at least 34 owned Chrome launches.
  assert.ok(
    ledger.historicalLowerBound.ownedChromeLaunches >= 34,
    `the historical lower bound is ${ledger.historicalLowerBound.ownedChromeLaunches}`,
  );
  // The COMBINED bound is the stage lifetime total PLUS the historical lower
  // bound: the two sets are disjoint, so nothing is counted twice.
  assert.equal(
    ledger.combinedLowerBound.ownedChromeLaunches,
    ledger.stageTotals.chromeLaunch + ledger.historicalLowerBound.ownedChromeLaunches,
  );
  // The per-source launch records are reported but NOT added.
  assert.ok(ledger.historicalLowerBound.perSourceLaunchRecordsNotAdded);
  assert.match(
    ledger.historicalLowerBound.perSourceLaunchRecordsNotAdded.note,
    /NOT ADDED/,
  );
  // No absolute path is ever reported.
  const serialized = JSON.stringify(summary);
  assert.ok(!serialized.includes("/tmp/navia-b5-3-seqstage"), "the summary must not carry the stage root path");
});

