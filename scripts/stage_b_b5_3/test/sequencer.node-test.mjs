//
// The sequencer is driven against a STUB runner that writes the real evidence
// files. No Chrome, no Runtime, no Provider, no audio, no network.
//
// The tests assert the PROCESS EXIT, not merely a summary field: a
// semantically failing aggregate (one failed, one limited, two blocked, a
// substituted identity, a stale artifact, a missing receipt, a missing
// required evidence file, an upload-policy violation or a leaked owned
// process) must never leave a zero exit behind.

