test("an OWNED descendant that exits before the closeout is still a leak", () => {
  const evidenceRoot = makeEvidenceRoot();
  // An UNRELATED live process: it belongs to another run and it may never be
  // counted, signalled or terminated by this one.
  const unrelated = spawn("bash", ["-c", "exec -a 'node run_one_bvid.mjs' sleep 30"], {
    stdio: "ignore",
  });
  // The descendant outlives its source runner. The sequencer cleans ONLY the
  // OWNED descendants, so the descendant is DEAD at the closeout: the
  // LATCHED sighting is the only surviving record of the boundary violation.
  const proc = driveSequencer({ stubMode: "owned-leak-late", evidenceRoot });
  const summary = summaryOf(evidenceRoot);
  try {
    assert.notEqual(proc.status, 0, "an owned leak must not leave a zero exit");
    assert.equal(summary.stopped, true);
    assert.match(summary.stopReason, /owned process leak/);
    // The sighting is preserved and it names the SOURCE that leaked.
    assert.ok(summary.processAudit, "the summary must carry the process audit");
    assert.equal(summary.processAudit.ok, false);
    assert.ok(summary.processAudit.leakedAfter > 0, "the latched sighting must survive");
    assert.ok(Array.isArray(summary.processAudit.sightings));
    assert.ok(summary.processAudit.sightings.length > 0);
    assert.equal(summary.processAudit.sightings[0].source, `1/${SIX[0]}`);
    // The owned descendant was cleaned: it is DEAD at the closeout, and the
    // latched sighting is what still fails the batch.
    assert.equal(summary.processAudit.stillAliveAtCloseout, 0);
    assert.ok(summary.processAudit.killedOwnedPids.length > 0, "the owned descendant must be cleaned");
    // The source row carries the leak: the aggregate may never be positive.
    assert.ok(summary.verdict, "the sequencer must write a verdict");
    assert.equal(summary.verdict.positive, false);
    assert.ok(
      summary.verdict.failures.some((failure) => failure.code === "AGG_AUDIT_FAILED"
        && /leaked an owned process/.test(failure.detail)),
      JSON.stringify(summary.verdict.failures),
    );
    // The batch stopped after the FIRST leak: the later sources never ran.
    assert.equal(summary.bvids.length, 1);
    // The UNRELATED process was never touched.
    assert.equal(unrelated.killed, false);
    assert.equal(unrelated.exitCode, null);
  } finally {
    unrelated.kill("SIGKILL");
  }
});

test("an UNRELATED live runner is neither counted nor killed", async () => {
  const evidenceRoot = makeEvidenceRoot();
  // A process whose argv names the runner, but that belongs to ANOTHER run.
  // The ownership audit must never count it and the test must never kill it.
  const unrelated = spawn("bash", ["-c", "exec -a 'node run_one_bvid.mjs' sleep 30"], {
    stdio: "ignore",
  });
  await new Promise((resolve) => setTimeout(resolve, 300));
  try {
    const proc = driveSequencer({ stubMode: "complete", evidenceRoot });
    const summary = summaryOf(evidenceRoot);
    assert.equal(summary.processAudit.ok, true, "an unrelated process is not a leak of this run");
    assert.equal(summary.processAudit.leakedAfter, 0);
    assert.equal(summary.processAudit.leakedBefore, 0);
    assert.equal(proc.status, 0, "an unrelated process must not fail this run");
    // The unrelated process is STILL alive: it was never killed.
    assert.equal(unrelated.killed, false);
    assert.equal(unrelated.exitCode, null);
  } finally {
    unrelated.kill("SIGKILL");
  }
});

