def evidence_item(index: int, start_ms: int, kind: str = "transcript") -> dict[str, Any]:
    return {
        "evidenceId": f"mtr_{index + 1:032d}",
        "kind": kind,
        "timestampStartMs": start_ms,
        "timestampEndMs": start_ms + 900,
        "text": f"第 {index + 1} 段派生字幕文本，包含可核验的事实陈述与时间范围说明。",
    }


def visible_shape_evidence(count: int = 96) -> list[dict[str, Any]]:
    """A synthetic catalog with MANY evidence rows, like the visible run."""
    return [evidence_item(index, index * 1_000) for index in range(count)]


def chapter(evidence_ids: list[str], *, relation: str = "continuation") -> dict[str, Any]:
    return {
        "title": "章节标题说明",
        "thesis": "章节核心结论的说明文字。",
        "evidenceIds": list(evidence_ids),
        "relationToPrevious": relation,
    }


def candidate(chapters: list[dict[str, Any]], evidence: list[dict[str, Any]]) -> dict[str, Any]:
    ids = [item["evidenceId"] for item in evidence]
    return {
        "brief": {
            "text": "视频完整讲述了背景、方法与结论，覆盖开头中段和结尾。",
            "evidenceIds": [ids[0], ids[len(ids) // 2], ids[-1]],
        },
        "claims": [
            {"text": "第一条可核验的核心表达，概括了视频的一个要点。", "evidenceIds": [ids[0]]},
            {"text": "第二条可核验的核心表达，说明了结论与适用边界。", "evidenceIds": [ids[-1]]},
        ],
        "chapters": chapters,
        "unresolvedEvidenceConflict": False,
    }


def clustered_chapters(evidence: list[dict[str, Any]], *, count: int = 6) -> list[dict[str, Any]]:
    """Six chapters whose anchors cluster at the START of the span."""
    ids = [item["evidenceId"] for item in evidence]
    picked = ids[: count - 1] + [ids[-1]]
    return [
        chapter([evidence_id], relation="opening" if index == 0 else "continuation")
        for index, evidence_id in enumerate(picked)
    ]


def balanced_chapters(evidence: list[dict[str, Any]], *, count: int = 6) -> list[dict[str, Any]]:
    """Six chapters spread over the whole span."""
    ids = [item["evidenceId"] for item in evidence]
    picked = [ids[round(index * (len(ids) - 1) / (count - 1))] for index in range(count)]
    return [
        chapter([evidence_id], relation="opening" if index == 0 else "continuation")
        for index, evidence_id in enumerate(picked)
    ]


def candidate_requests(requests: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """The candidate requests only: the chunk extraction is a different task."""
    return [
        request for request in requests
        if request.get("task") != "extract_grounded_chapter_candidates"
    ]


def fake_provider(bodies: list[Any]) -> tuple[MiniMaxGroundedSynthesisProvider, list[dict[str, Any]]]:
    """The REAL adapter with a fake HTTP transport."""
    remaining = list(bodies)
    requests: list[dict[str, Any]] = []

    def handler(request: httpx.Request) -> httpx.Response:
        envelope = json.loads(request.content.decode("utf-8"))
        user_content = envelope["messages"][-1]["content"]
        payload = json.loads(user_content)
        requests.append(payload)
        if payload.get("task") == "extract_grounded_chapter_candidates":
            body: Any = CHUNK_BODY
        else:
            body = remaining.pop(0) if remaining else {"summary": "no more bodies"}
        if isinstance(body, Exception):
            raise body
        return httpx.Response(
            200,
            json={
                "choices": [
                    {"message": {"content": json.dumps(body, ensure_ascii=False)}, "finish_reason": "stop"}
                ],
                "usage": {"prompt_tokens": 10, "completion_tokens": 20},
            },
        )

    provider = MiniMaxGroundedSynthesisProvider(
        dict(PROVIDER),
        client_factory=lambda: httpx.Client(transport=httpx.MockTransport(handler)),
    )
    return provider, requests


def validate(candidate_value: dict[str, Any], evidence: list[dict[str, Any]]) -> dict[str, Any]:
    """The UNCHANGED independent V2.1 validator."""
    ordered = sorted(evidence, key=lambda item: (item["timestampStartMs"], item["evidenceId"]))
    return validate_grounded_comprehension(
        candidate_value,
        ordered,
        task_id="media_task_" + "1" * 32,
        task_revision=1,
        source_identity="portal:bilibili:BV1TEST00001:1:p1",
        evidence_catalog_sha256="0" * 64,
        media_duration_ms=max(item["timestampEndMs"] for item in ordered),
        receipt={
            "providerId": "minimax-cn-openai-vision",
            "modelId": "MiniMax-M3",
            "outboundDerivedTextSha256": "1" * 64,
            "requestCount": 1,
        },
        schema_version="v3-media-grounded-comprehension/v2.1",
    )


