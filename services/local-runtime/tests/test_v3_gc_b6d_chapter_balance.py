def test_b6d1_the_concentration_rule_accepts_the_exact_threshold() -> None:
    """B6D-1 — 3 of 6 anchors in one window is EXACTLY the allowed ratio."""
    # The span is 6000 ms, so the concentration window is 1200 ms.
    anchors = [0, 400, 800, 3_600, 4_800, 6_000]
    assessment = assess_chapter_balance(
        anchors=anchors,
        span_start_ms=0,
        span_end_ms=6_000,
        substantive_region_count=3,
    )
    assert assessment.chapter_count == 6
    assert assessment.concentration == pytest.approx(0.5)
    assert assessment.violation_class is None
    assert assessment.violation_code is None
    assert assessment.ok is True


def test_b6d1_the_concentration_rule_refuses_one_over_the_threshold() -> None:
    """B6D-1 — 4 of 6 anchors in one window is ONE OVER the allowed ratio."""
    anchors = [0, 400, 800, 1_000, 4_800, 6_000]
