SERVICE_TASK = "media_task_" + "5" * 32
SERVICE_SOURCE = "portal:bilibili:BV1test5xx:41828944992:1"


class _ClusteredProjection:
    """A projection with a CLUSTERED head and a long tail.

    The transcript buckets of the materializer therefore produce evidence
    rows that sit close together at the start of the span: the shape of the
    visible run.
    """

    def get(self, task_id: str) -> dict[str, Any]:
        segments = []
        for index in range(60):
            start = index * 100
            segments.append({
                "segmentId": f"seg_{index}",
                "startMs": start,
                "endMs": start + 90,
                "text": f"开头部分第 {index + 1} 条转写证据，说明视频背景与讨论范围。",
            })
        for index in range(36):
            start = 100_000 + index * 100_000
            segments.append({
                "segmentId": f"tail_{index}",
                "startMs": start,
                "endMs": start + 90,
                "text": f"后段第 {index + 1} 条转写证据，说明结论与适用边界。",
            })
        return {
            "taskId": task_id,
            "sourceIdentity": SERVICE_SOURCE,
            "state": "succeeded",
            "terminal": True,
            "segments": segments,
        }


def _service(tmp_path: Path, provider: Any):
    from navia_runtime.modules.media_companion.comprehension import MediaComprehensionService
    from navia_runtime.modules.media_companion.product_materializer import MediaProductMaterializer
    from navia_runtime.modules.media_companion.task_store import MediaTaskStore

    store = MediaTaskStore(tmp_path / "runtime.sqlite3")
    private = tmp_path / "private"
    task = MediaProductMaterializer(store, _ClusteredProjection(), private).materialize(SERVICE_TASK)
    return store, private, task, MediaComprehensionService(
        store,
        private,
        synthesis_provider_factory=lambda: provider,
    )


def _service_candidate(evidence: list[dict[str, Any]], *, clustered: bool) -> dict[str, Any]:
    ids = [item["evidenceId"] for item in evidence]
    if clustered:
        # The CLUSTERED head of the span: five anchors sit inside one fifth
        # of it and the last chapter still covers the end of the evidence.
        picked = ids[:5] + [ids[-1]]
    else:
        # The anchors are spread over the whole span.
        picked = [ids[0], ids[10], ids[12], ids[15], ids[18], ids[-1]]
    chapters = [
        chapter([evidence_id], relation="opening" if index == 0 else "continuation")
        for index, evidence_id in enumerate(picked)
    ]
    value = candidate(chapters, evidence)
    value["brief"]["evidenceIds"] = [ids[0], ids[10], ids[-1]]
    return value


