def test_b6d6_a_terminal_imbalance_leaves_the_previous_product_unchanged(tmp_path) -> None:
    """B6D-6 — a terminal imbalance publishes NOTHING and changes NOTHING."""
    store, private, task, service = _service(tmp_path, None)
    catalog = store.get(SERVICE_TASK)["projections"]["evidenceCatalog"]
    evidence = [
        {
            "evidenceId": item["evidenceId"],
            "kind": item["kind"],
            "timestampStartMs": item["timestampStartMs"],
            "timestampEndMs": item["timestampEndMs"],
            "text": "派生文本，用于服务级测试。",
        }
        for item in catalog
    ]
    clustered = _service_candidate(evidence, clustered=True)
    balanced = _service_candidate(evidence, clustered=False)
    # The FIRST publish succeeds and becomes the previous durable product.
    provider, _ = fake_provider([balanced])
    store, private, task, service = _service(tmp_path, provider)
    service.synthesize(SERVICE_TASK, task["revision"], True, "structured")
    published = private / "grounded-comprehension-v2.1" / SERVICE_TASK
    before = {path.name: path.read_bytes() for path in published.rglob("*") if path.is_file()}
    assert before, "the first publish must have produced a durable product"

    # The SECOND attempt is a persistent imbalance: it must publish NOTHING.
    provider, _ = fake_provider([clustered] * 12)
    store, private, task, service = _service(tmp_path, provider)
    with pytest.raises(MediaTaskStoreError) as error:
        service.synthesize(SERVICE_TASK, task["revision"], True, "structured")
    assert error.value.code == "V3510B_CHAPTER_IMBALANCE"
    after = {path.name: path.read_bytes() for path in published.rglob("*") if path.is_file()}
    assert after == before, "the previous durable product must be unchanged"
    # The INTERNAL diagnostic of the final refusal is retrievable.
    diagnostic = private / "diagnostics" / SERVICE_TASK / "stage-b-diagnostic.json"
    assert diagnostic.exists(), "the service must write the internal diagnostic"
    written = json.loads(diagnostic.read_text(encoding="utf-8"))
    assert written["stages"][-1]["failureCode"] == "V3510B_CHAPTER_IMBALANCE"
    assert max(
        stage.get("providerOutboundHttpAttempts") or 0
        for stage in written["stages"]
    ) > 0
